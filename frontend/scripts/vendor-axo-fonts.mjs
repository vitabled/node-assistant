// Vendors the Axottle typography (Manrope variable + Unbounded variable) into
// src/assets/fonts/ and emits src/fonts-axottle.css.
//
// Why a manual script (and NOT a build step): the panel must build offline.
// fonts.googleapis.com is reached once, here, and the result is committed —
// exactly like the Inter/JetBrains Mono files in src/fonts.css. Re-run only when
// a family/weight range changes:
//
//   node scripts/vendor-axo-fonts.mjs
//
// Source of the family choice: Axottle's public CSS declares
//   --font-manrope:"Manrope","Manrope Fallback"   (sans)
//   --font-unbounded:"Unbounded","Unbounded Fallback" (display headings)
// Both are Google Fonts variable fonts; the subsets kept are the ones the panel
// actually needs (cyrillic, cyrillic-ext, latin, latin-ext) — greek/vietnamese
// are dropped to keep the payload small.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "src", "assets", "fonts");
const cssPath = path.join(root, "src", "fonts-axottle.css");

const KEEP = ["cyrillic-ext", "cyrillic", "latin-ext", "latin"];
const UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";
const URL_API =
  "https://fonts.googleapis.com/css2?family=Manrope:wght@200..800&family=Unbounded:wght@200..900&display=swap";

fs.mkdirSync(outDir, { recursive: true });

const css = await (await fetch(URL_API, { headers: { "User-Agent": UA } })).text();

// Blocks look like:
//   /* cyrillic */\n@font-face {\n  font-family: 'Manrope';\n ... src: url(https://…woff2) ...;\n  unicode-range: U+0301, …;\n}
const blocks = css.split("@font-face").slice(1).map(b => "@font-face" + b.slice(0, b.indexOf("}") + 1));
const chunks = [];

for (const raw of blocks) {
  const before = css.slice(0, css.indexOf(raw));
  const label = (before.match(/\/\*\s*([a-z-]+)\s*\*\/\s*$/) || [])[1] || "";
  if (!KEEP.includes(label)) continue;

  const family = (raw.match(/font-family:\s*'([^']+)'/) || [])[1];
  const weight = (raw.match(/font-weight:\s*([^;]+);/) || [])[1];
  const url = (raw.match(/url\((https:[^)]+)\)/) || [])[1];
  const range = (raw.match(/unicode-range:\s*([^;]+);/) || [])[1];
  if (!family || !url) continue;

  const fileName = `${family.replace(/\s+/g, "")}-var-${label}.woff2`;
  const dest = path.join(outDir, fileName);
  if (!fs.existsSync(dest) || fs.statSync(dest).size === 0) {
    const buf = Buffer.from(await (await fetch(url, { headers: { "User-Agent": UA } })).arrayBuffer());
    fs.writeFileSync(dest, buf);
    console.log(`downloaded ${fileName} (${(buf.length / 1024).toFixed(1)} KB)`);
  }

  chunks.push(
    `/* ${label} */\n@font-face {\n  font-family: '${family}';\n  font-style: normal;\n` +
    `  font-weight: ${weight};\n  font-display: swap;\n` +
    `  src: url('./assets/fonts/${fileName}') format('woff2');\n  unicode-range: ${range};\n}\n`,
  );
}

const header =
  `/* Self-hosted Axottle display/sans webfonts (Manrope variable, Unbounded variable).\n` +
  ` * Generated by scripts/vendor-axo-fonts.mjs from the Google Fonts css2 API — same files and\n` +
  ` * unicode-range subsets the Axottle stylesheets reference via --font-manrope / --font-unbounded.\n` +
  ` * Served from our own origin; do not hand-edit.\n */\n\n`;

fs.writeFileSync(cssPath, header + chunks.join("\n"));
console.log(`wrote ${path.relative(root, cssPath)} with ${chunks.length} @font-face blocks`);
